#!/usr/bin/env node
/**
 * Desktop build (M5-4, N1): bundle main + preload, then lay out the renderer.
 *
 * Why esbuild and not `tsc`: electron-builder's `files` list ships only
 * `apps/desktop/dist/**` and `package.json`, so every workspace package
 * (`@ytvdlt/shared`, `@ytvdlt/core`, `@ytvdlt/engine-ytdlp`) has to be inlined
 * into one JS file. `tsc` cannot bundle, and adding a bundler to
 * `devDependencies` would break the D-61 allow-list — so this script uses the
 * esbuild that vite already installed (`node_modules/.pnpm/esbuild@*`), which
 * adds no dependency to the lockfile.
 *
 * Output layout (relative to `apps/desktop/dist`):
 *   main/main.cjs       CommonJS entry, `electron` external
 *   preload/bridge.cjs  CommonJS preload (sandbox-compatible)
 *   pages/… styles/… i18n/… theme/… shortcuts/… app-shell.js  (copied from packages/ui/src)
 *   icon.ico            tray + installer icon (generated by scripts/make-icon.mjs)
 *
 *   node scripts/build-desktop.mjs
 */
import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const APP = join(ROOT, 'apps', 'desktop');
const DIST = join(APP, 'dist');

/** Resolve the esbuild that vite brought in; no new dependency is added. */
async function loadEsbuild() {
  const store = join(ROOT, 'node_modules', '.pnpm');
  const candidates = readdirSync(store)
    .filter((name) => name.startsWith('esbuild@'))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  if (candidates.length === 0) throw new Error('esbuild not found under node_modules/.pnpm');
  const entry = join(store, candidates[candidates.length - 1], 'node_modules', 'esbuild', 'lib', 'main.js');
  const mod = await import(pathToFileURL(entry).href);
  return mod.build === undefined ? mod.default : mod;
}

const alias = {
  '@ytvdlt/shared': join(ROOT, 'packages', 'shared', 'src', 'index.ts'),
  '@ytvdlt/core': join(ROOT, 'packages', 'core', 'src', 'index.ts'),
  '@ytvdlt/engine-ytdlp': join(ROOT, 'packages', 'engine-ytdlp', 'src', 'index.ts'),
};

const common = {
  bundle: true,
  platform: 'node',
  target: 'node22',
  // D-75: electron-updater IS bundled from now on. electron-builder's `files`
  // glob ships only `apps/desktop/dist/**` + `package.json` (design §6.2-⑥
  // forbids changing it), so a runtime `require('electron-updater')` could never
  // resolve inside the asar — A-4.4-29 was blocked on exactly that. Inlining it
  // keeps the glob untouched and puts the updater in the one file we already
  // ship. The module is still imported lazily, so the cost is bundle size
  // (~1 MB) rather than start-up work.
  external: ['electron'],
  alias,
  logLevel: 'warning',
  legalComments: 'none',
  charset: 'utf8',
};

function assertFile(path, label) {
  if (!existsSync(path) || !statSync(path).isFile()) {
    throw new Error(`${label} missing after build: ${path}`);
  }
}

async function main() {
  const esbuild = await loadEsbuild();
  rmSync(DIST, { recursive: true, force: true });
  mkdirSync(join(DIST, 'main'), { recursive: true });
  mkdirSync(join(DIST, 'preload'), { recursive: true });

  await esbuild.build({
    ...common,
    entryPoints: [join(APP, 'src', 'main', 'main.ts')],
    // CommonJS: Electron's builtin module offers no named ESM exports
    // (`import { app } from 'electron'` throws in the main process), and CJS
    // gives `__dirname` without an `import.meta` polyfill.
    outfile: join(DIST, 'main', 'main.cjs'),
    format: 'cjs',
  });

  await esbuild.build({
    ...common,
    entryPoints: [join(APP, 'src', 'preload', 'index.ts')],
    outfile: join(DIST, 'preload', 'bridge.cjs'),
    format: 'cjs',
  });

  // Renderer: the pages reference `../../styles/...`, `../../i18n/...`, so the
  // whole `packages/ui/src` tree is copied one level up from `pages/`.
  cpSync(join(ROOT, 'packages', 'ui', 'src'), DIST, { recursive: true });

  const icon = join(APP, 'build', 'icon.ico');
  if (existsSync(icon)) cpSync(icon, join(DIST, 'icon.ico'));

  assertFile(join(DIST, 'main', 'main.cjs'), 'main bundle');
  assertFile(join(DIST, 'preload', 'bridge.cjs'), 'preload bundle');
  assertFile(join(DIST, 'pages', 'queue', 'index.html'), 'queue page');

  const size = (path) => `${(statSync(path).size / 1024).toFixed(1)} KB`;
  console.log(`[build-desktop] main   ${size(join(DIST, 'main', 'main.cjs'))}`);
  console.log(`[build-desktop] preload ${size(join(DIST, 'preload', 'bridge.cjs'))}`);
  console.log(`[build-desktop] renderer pages/styles/i18n copied`);
}

await main();
